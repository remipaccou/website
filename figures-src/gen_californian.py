w(rf"\draw[black!35, line width=0.35pt] {P(1993, CO - 0.1)} -- {P(1993, CO - 0.46)};")
for y, h, sym, text, anchor, dx, dy in EV:
    w(rf"\{sym}{{{P(y, h)}}}")
    w(rf"\node[lab, anchor={anchor}] at ({f(X(y) + dx)},{f(h + dy)}) {{{text}}};")

# Legend, under the axis, in rows of three.
leg_y = -0.95
items = [
    (r'\nd{(0,0)}', 'put into service'),
    (r'\nb{(0,0)}', 'an idea, a study, a demonstration'),
    (r'\lz{(0,0)}', 'who owns it changes'),
    (r'\dc{(0,0)}', 'a diagnosis'),
    (r'\node[inner sep=0.5pt] at (0,0) {\textdagger};', 'a lineage ends'),
    (r'\draw[passe] (-0.25,0) -- (0.25,0);', 'the same thing passes on (a language, a network, an ethos)'),
    (r'\draw[gens] (-0.25,0) -- (0.25,0);', 'people and skills move'),
    (r'\draw[idee] (-0.25,0) -- (0.25,0);', 'an idea attached later'),
    (r'\node[inner sep=0.5pt] at (0,0) {*};', 'the date is not in the essay'),
]
cols = [0.4, 6.4, 13.4]
for i, (sym, text) in enumerate(items):
    cx, cy = cols[i % 3], leg_y - 0.38 * (i // 3)
    w(rf"\begin{{scope}}[shift={{({cx},{f(cy)})}}] {sym} \node[anchor=west, inner sep=1pt] at (0.35,0) {{{text}}}; \end{{scope}}")

w(r"\end{tikzpicture}")
(Path(__file__).resolve().parent / 'californian.en.tex').write_text('\n'.join(out) + '\n', encoding='utf-8')
