    (2001, CO, 'nd', '2001* Wikipedia', 'south west', -0.08, 0.12),                        # text
    (1995, DG, 'dc', '1995 Barbrook \\& Cameron,\\\\\\emph{The Californian Ideology}', 'south west', -0.1, 0.12),  # text
    (2006, DG, 'dc', '2006 Turner', 'north east', 0.1, -0.14),                            # ref 2
    (2017, DG, 'dc', '2017 Srnicek,\\\\platform capitalism', 'south east', 0.05, 0.12),     # ref 26
